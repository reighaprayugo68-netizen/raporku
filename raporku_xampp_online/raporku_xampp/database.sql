CREATE DATABASE IF NOT EXISTS raporku
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE raporku;

CREATE TABLE IF NOT EXISTS kelas (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(50) NOT NULL UNIQUE,
  tingkat TINYINT NOT NULL,
  keterangan VARCHAR(150) NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS tahun_ajaran (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(20) NOT NULL UNIQUE,
  semester ENUM('Ganjil','Genap') NOT NULL DEFAULT 'Ganjil',
  aktif TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS mata_pelajaran (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(100) NOT NULL UNIQUE,
  kode VARCHAR(20) NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS siswa (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nis VARCHAR(30) NOT NULL UNIQUE,
  nisn VARCHAR(30) NULL UNIQUE,
  nama VARCHAR(120) NOT NULL,
  jenis_kelamin ENUM('L','P') NULL,
  alamat TEXT NULL,
  kelas_id INT NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_siswa_kelas FOREIGN KEY (kelas_id) REFERENCES kelas(id)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(60) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role ENUM('admin','siswa') NOT NULL DEFAULT 'siswa',
  siswa_id INT NULL UNIQUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_user_siswa FOREIGN KEY (siswa_id) REFERENCES siswa(id)
    ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS nilai (
  id INT AUTO_INCREMENT PRIMARY KEY,
  siswa_id INT NOT NULL,
  mapel_id INT NOT NULL,
  tahun_ajaran_id INT NOT NULL,
  nilai DECIMAL(5,2) NOT NULL,
  predikat VARCHAR(5) NOT NULL,
  catatan VARCHAR(255) NULL,
  UNIQUE KEY unik_nilai (siswa_id, mapel_id, tahun_ajaran_id),
  CONSTRAINT fk_nilai_siswa FOREIGN KEY (siswa_id) REFERENCES siswa(id)
    ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT fk_nilai_mapel FOREIGN KEY (mapel_id) REFERENCES mata_pelajaran(id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_nilai_tahun FOREIGN KEY (tahun_ajaran_id) REFERENCES tahun_ajaran(id)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;
